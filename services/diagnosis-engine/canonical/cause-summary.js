/** The summary label for a canonical cause key, or null (never the key itself). */
function causeSummary(cause) {
  return typeof cause === 'string' && Object.prototype.hasOwnProperty.call(CAUSE_SUMMARY, cause) ? CAUSE_SUMMARY[cause] : null;
}

/** A journey summary whose NextAction conclusion carries its summary label (a new object; the input is untouched). */
function journeyWithCauseSummary(journey) {
  const a = journey && journey.nextAction;
  const c = a && a.conclusion;
  if (!c || typeof c !== 'object') return journey;
  return { ...journey, nextAction: { ...a, conclusion: { ...c, summary: causeSummary(c.cause) } } };
}

module.exports = { CAUSE_SUMMARY, causeSummary, journeyWithCauseSummary };
